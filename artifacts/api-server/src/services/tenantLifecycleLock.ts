import { sql, eq } from "drizzle-orm";
import { crechesTable } from "@workspace/db/schema";

/**
 * TENANT LIFECYCLE ADVISORY LOCK COORDINATOR (LEVEL 1)
 *
 * Global Lock Hierarchy (Strict Ordering):
 *   LEVEL 0: Scheduler Global Lock (999100001, bigint)
 *   LEVEL 1: Tenant Lifecycle Lock (-9812, crecheId) (Shared: all tenant mutations / Exclusive: Archive & Restore)
 *   LEVEL 2: Campaign Tutor Lock (hashtext('campaign_redemption_' || crecheId || '_' || tutorId), bigint)
 *   LEVEL 3: Financial Tutor Lock (crecheId, tutorId) (int4, int4)
 *   LEVEL 4: Resource Row Locks (FOR UPDATE: invoices -> orders -> catalogue -> credits -> bookings -> pets -> tasks/feed/chat)
 *
 * Advisory Namespace Isolation Classification:
 *   PROVEN_BY_APPLICATION_INVARIANT
 *
 * Namespace isolation against single-key advisory locks (Level 0, Level 2) is proven by the
 * PostgreSQL kernel lock manager (locktag_field4 = 2 for two-integer keys vs locktag_field4 = 1 for bigint).
 * Isolation against two-key financial tutor locks (crecheId, tutorId) is PROVEN_BY_APPLICATION_INVARIANT:
 * all tenant IDs generated by the creches_id_seq sequence through current application creation paths
 * are positive integers >= 1, and since TENANT_LIFECYCLE_ADVISORY_NAMESPACE = -9812 < 0, key collision
 * is impossible. (Note: the schema currently has no explicit CHECK (id > 0) constraint, which is deferred
 * to future schema hardening under R38.A zero-DDL rule).
 */
export const TENANT_LIFECYCLE_ADVISORY_NAMESPACE = -9812;

export class TenantArchivedError extends Error {
  statusCode = 403;
  status = 403;
  code = "tenant_archived";

  constructor(message = "Esta creche foi arquivada e não aceita mais operações.") {
    super(message);
    this.name = "TenantArchivedError";
  }
}

/**
 * Acquires a shared advisory lock on the tenant lifecycle namespace at the outermost
 * transaction boundary and revalidates the tenant's committed status.
 *
 * If the tenant is archived, throws TenantArchivedError (HTTP 403).
 * Lock is automatically released at transaction end (commit or rollback).
 */
export async function acquireTenantOperationalLock(crecheId: number, tx: any): Promise<void> {
  if (!crecheId || isNaN(crecheId)) return;

  // Level 1: Shared advisory transaction lock
  await tx.execute(
    sql`SELECT pg_advisory_xact_lock_shared(${TENANT_LIFECYCLE_ADVISORY_NAMESPACE}, ${crecheId})`
  );

  // Status revalidation: check if archival committed while waiting or prior
  const [creche] = await tx
    .select({ status: crechesTable.status })
    .from(crechesTable)
    .where(eq(crechesTable.id, crecheId))
    .limit(1);

  if (creche && creche.status === "archived") {
    throw new TenantArchivedError();
  }
}

/**
 * Acquires an exclusive advisory lock on the tenant lifecycle namespace at the outermost
 * transaction boundary. Used exclusively for Tenant Archive and Tenant Restore operations.
 *
 * Lock is automatically released at transaction end (commit or rollback).
 */
export async function acquireTenantLifecycleLock(crecheId: number, tx: any): Promise<void> {
  if (!crecheId || isNaN(crecheId)) return;

  // Level 1: Exclusive advisory transaction lock
  await tx.execute(
    sql`SELECT pg_advisory_xact_lock(${TENANT_LIFECYCLE_ADVISORY_NAMESPACE}, ${crecheId})`
  );
}
