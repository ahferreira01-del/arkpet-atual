export function getNavigationItemsForRole(role: UserRole): NavigationItem[] {
  return NAVIGATION_CONFIG.filter((item) => item.roles.includes(role)).sort(
    (a, b) => (a.order ?? 99) - (b.order ?? 99)
  );
}

export function getDesktopNavigationItems(role: UserRole): NavigationItem[] {
  return getNavigationItemsForRole(role).filter((item) => item.desktop !== false);
}

export function getMobileNavigationItems(role: UserRole): NavigationItem[] {
  return getNavigationItemsForRole(role).filter((item) => item.mobile !== false);
}
